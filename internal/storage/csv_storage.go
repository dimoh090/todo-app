// В этом файле будут функции сохранения и загрузки задач в формате CSV.
package storage

// Подключаем стандартный пакет для чтения и записи CSV.

// Подключаем стандартный пакет для работы с файлами и операционной системой.
import (
	"encoding/csv"
	"fmt"
	"os"

	// Подключаем наш пакет todo, чтобы использовать тип Task.
	"todo-app/internal/todo"
	// Подключаем преобразование чисел и логических знаний в текст и обратно.
	"strconv"
)

// SaveCSV сохраняем список задач в CSV-файл и сообщаем об ошибке.
func SaveCSV(path string, tasks []todo.Task) error {

	// Создаем и открываем файл. Если он уже существует, очищаем его содержимое.
	file, err := os.Create(path)

	// Если создать файл и не удалось, завершить функцию и возвращаем ошибку.
	if err != nil {
		return err
	}

	// Закрываем файл перед возвратом из SaveCSV, включая возврат ошибки.
	defer file.Close()

	// Создаем объект, который будет записывать строки CVS в открытый файл.
	writer := csv.NewWriter(file)

	// Подготавливаем название столбцов для первой строки CSV.
	header := []string{"ID", "Description", "Done"}

	// Передаем заголовой CSV-писателю и сохраняем возможную ошибку.
	err = writer.Write(header)

	// Если CVS-писатель сообщил об ошибке, прекращаем сохранение.
	if err != nil {
		return err
	}

	// По очереди обрабатываем каждую задачу для записи в CSV.
	for _, task := range tasks {

		// Преобразуем номер текущей задачи из целого числа в текст для CSV.
		idText := strconv.Itoa(task.ID)

		// Преобразуем статус выполнения из bool в текст для записи в CSV.
		doneTest := strconv.FormatBool(task.Done)

		// Собираем значение одной задачи в порядок столбцов CVS.
		record := []string{idText, task.Description, doneTest}

		// Передаем поля текущей задачи CSV-писателю и сохраняем возвождую ошибку.
		err = writer.Write(record)

		// Если запись задачи завершилась ошибкой, прекращаем сохранение и возвращаем её.
		if err != nil {
			return err
		}
	}
	// Передаем накопленные CSV-данные из буфера в файл.
	writer.Flush()

	// Получем возможную ошибку в записи CSV после передачи буфера в файл.
	err = writer.Error()

	// Если CSV-писатель сообщил об ошибке, прекращаем сохранение и возвращаем её.
	if err != nil {
		return err
	}

	// Закрываем файл и получаем возможную ошибку закрытия.
	err = file.Close()
	// Завершаем SaveCSV: возвращаем ошибку закрытия или nil.
	return err

}

// LoadCSV загружает задачи из CSV-файла и возвразает список задач и возможную ошибку.
func LoadCSV(path string) ([]todo.Task, error) {
	// Открываем существующий файл для чтения и получаем возможнокую ошибку.
	file, err := os.Open(path)

	// Если открыть файл не удалось, завершаем загрузгу и возвращаем ошибку.
	if err != nil {
		return nil, err
	}

	// Откладываем закрытие открытого файла до выхода из LoadCSV.
	defer file.Close()

	// Создаем CSV-читатель, который будет разбирать строки открытого файла.
	reader := csv.NewReader(file)

	// Читаем всё CSV-записи и получаем возможную ошибку чтения.
	records, err := reader.ReadAll()

	// Если прочитать CSV не удалось, завершаем загрузку и возвращаем ошибку.
	if err != nil {
		return nil, err
	}

	// Подготавливаем пустой список, в который будет складывать задач.
	tasks := []todo.Task{}

	// Если файл пустой, возвращаем пустой список без ошибки.
	if len(records) == 0 {
		return tasks, nil
	}

	// Перебирает записи, начиная со второй, чтобы пропустить заголовок CSV.
	for _, record := range records[1:] {
		// У каждой задачи в CVS должы быть три поля: ID, описание и статус.
		if len(record) != 3 {
			return nil, fmt.Errorf("в CSV-записи должно быть 3 поля, найдено: %d", len(record))
		}

		// Преобразуем первое поле CSV - ID -из текста в целое число.
		id, parseErr := strconv.Atoi(record[0])

		// Если ID не удалось превратить в число, возвращаем понятную ошибку.
		if parseErr != nil {
			return nil, fmt.Errorf("неверный ID %q: %w", record[0], parseErr)
		}
		// Преобразуем третье после CSV - статус -из текста в true или false.
		done, parseErr := strconv.ParseBool(record[2])

		// Если статус не удалось преобразовать в true или false, возвращаем ошибку.
		if parseErr != nil {
			return nil, fmt.Errorf("неверный статус задачи %q: %w", record[2], parseErr)
		}

		// Собираем одну задачу из преобразованных данных CSV.
		task := todo.Task{
			ID: id, Description: record[1], Done: done,
		}

		// Добавляем готовую задачу в общий список.
		tasks = append(tasks, task)

	}
	// Возвращаем собранный список и сообщаем, что ошибок нет.
	return tasks, nil
}
